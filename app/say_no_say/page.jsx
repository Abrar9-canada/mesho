export default function SayNotToSayGame() {
  const [currentSentence, setCurrentSentence] = useState('اضغط "جملة جديدة" لبدء التحدي!');
  const [copiedMsg, setCopiedMsg] = useState('');
  const [usedIndices, setUsedIndices] = useState([]);

  const getRandomSentence = () => {
    if (usedIndices.length >= sentencesList.length) {
      setCurrentSentence('لقد استهلكت جميع الجمل! اضغط "إعادة تعيين" للبدء من جديد.');
      return;
    }

    let randomIndex;
    do {
      randomIndex = Math.floor(Math.random() * sentencesList.length);
    } while (usedIndices.includes(randomIndex));

    setUsedIndices([...usedIndices, randomIndex]);
    setCurrentSentence(sentencesList[randomIndex]);
    setCopiedMsg('');
  };

  const resetGame = () => {
    setUsedIndices([]);
    setCurrentSentence('اضغط "جملة جديدة" لبدء التحدي!');
    setCopiedMsg('');
  };

  const copySentence = () => {
    if (currentSentence.includes('اضغط') || currentSentence.includes('استهلكت')) return;
    navigator.clipboard.writeText(currentSentence);
    setCopiedMsg('تم النسخ بنجاح! 📋');
    setTimeout(() => setCopiedMsg(''), 2500);
  };

  return (
    <div dir="rtl" className="min-h-screen bg-[#0d021a] text-white flex flex-col items-center justify-center p-4 md:p-8 font-sans">
      
      <div className="absolute top-4 right-4">
        <a href="/" className="bg-[#18052c] border border-purple-500/40 text-pink-300 text-xs px-4 py-2 rounded-xl hover:bg-purple-900/50 transition">
          🏠 العودة للصالة
        </a>
      </div>

      <div className="flex items-center gap-2 mb-8">
        <span className="text-2xl">🎮</span>
        <h1 className="text-2xl md:text-3xl font-extrabold text-transparent bg-clip-text bg-gradient-to-r from-pink-400 to-purple-300">
          قول بس لا تقول
        </h1>
      </div>

      {copiedMsg && (
        <div className="bg-emerald-600/90 text-white px-4 py-1.5 rounded-xl mb-4 text-sm font-bold animate-pulse shadow-lg">
          {copiedMsg}
        </div>
      )}

      <div className="flex flex-wrap justify-center gap-3 mb-6">
        <button 
          onClick={getRandomSentence}
          className="bg-gradient-to-r from-pink-500 to-purple-600 hover:opacity-90 transition px-5 py-2.5 rounded-xl font-bold shadow-md flex items-center gap-2 text-sm md:text-base">
          🔄 جملة جديدة
        </button>
        <button 
          onClick={copySentence}
          className="bg-purple-900/80 border border-purple-500/50 hover:bg-purple-800 transition px-5 py-2.5 rounded-xl font-bold shadow-md flex items-center gap-2 text-sm md:text-base">
          📋 نسخ
        </button>
        <button 
          onClick={resetGame}
          className="bg-red-950/80 border border-red-500/50 hover:bg-red-900 transition px-5 py-2.5 rounded-xl font-bold shadow-md flex items-center gap-2 text-sm md:text-base">
          ♻️ إعادة تعيين
        </button>
      </div>

      <div className="w-full max-w-3xl min-h-[180px] bg-[#18052c] border border-pink-500/40 rounded-2xl p-6 md:p-10 flex items-center justify-center text-center shadow-2xl relative overflow-hidden transition-all">
        <p className="text-lg md:text-2xl font-bold leading-relaxed text-pink-100 tracking-wide">
          {currentSentence}
        </p>
      </div>

      <div className="mt-4 text-xs text-purple-400">
        الجمل المستخدمة: {usedIndices.length} من {sentencesList.length}
      </div>

    </div>
  );
}